/// Comparison key for search boxes. Accents match the plain letter: jamón and jamon.
String foldSearchText(String? value) {
  const replacements = <int, int>{
    0x00E1: 0x61, // á
    0x00E0: 0x61, // à
    0x00E4: 0x61, // ä
    0x00E2: 0x61, // â
    0x00E3: 0x61, // ã
    0x00E5: 0x61, // å
    0x00E9: 0x65, // é
    0x00E8: 0x65, // è
    0x00EB: 0x65, // ë
    0x00EA: 0x65, // ê
    0x00ED: 0x69, // í
    0x00EC: 0x69, // ì
    0x00EF: 0x69, // ï
    0x00EE: 0x69, // î
    0x00F3: 0x6F, // ó
    0x00F2: 0x6F, // ò
    0x00F6: 0x6F, // ö
    0x00F4: 0x6F, // ô
    0x00F5: 0x6F, // õ
    0x00FA: 0x75, // ú
    0x00F9: 0x75, // ù
    0x00FC: 0x75, // ü
    0x00FB: 0x75, // û
    0x00FD: 0x79, // ý
    0x00FF: 0x79, // ÿ
    0x00F1: 0x6E, // ñ
    0x00E7: 0x63, // ç
  };

  final buffer = StringBuffer();
  for (final rune in (value ?? '').toLowerCase().runes) {
    if (rune >= 0x0300 && rune <= 0x036F) continue;
    buffer.writeCharCode(replacements[rune] ?? rune);
  }
  return buffer.toString().trim();
}
